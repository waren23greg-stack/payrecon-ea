"""Database layer for payrecon-ea: DDL generation, connections, one DB per run.

The staging tables are generated from schema.py, so the column contract has a
single source of truth. Staging is deliberately permissive: no CHECK constraints
on enum columns and no UNIQUE on the payment line key, because the SQL checks
need to see dirty rows to report them. Only what makes a row impossible to
store (NOT NULL on required columns, foreign keys, one load per file) is
enforced here. Strict constraints belong in a later curated layer.

SQLite is the zero-setup default. render_ddl("postgres") produces the same
tables for the production path; each run gets its own database file, so
concurrent runs never contend for a write lock.

Regenerate the committed DDL files with:
    python -m payrecon.db ddl sqlite sql/schema.sqlite.sql
    python -m payrecon.db ddl postgres sql/schema.postgres.sql
"""

from __future__ import annotations

import re
import secrets
import sqlite3
import sys
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import TextIO

from payrecon.schema import ORDER_COLUMNS, PAYMENT_COLUMNS, PAYMENT_KEY, Column

SCHEMA_VERSION = "1"
DIALECTS = ("sqlite", "postgres")
_RUN_ID = re.compile(r"^[A-Za-z0-9_-]{1,64}$")


def _type(sql_type: str, dialect: str) -> str:
    # SQLite integers are 64-bit already; PostgreSQL INTEGER is 32-bit and minor
    # units overflow it for large UGX or TZS amounts.
    return "BIGINT" if dialect == "postgres" and sql_type == "INTEGER" else sql_type


def _contract(columns: tuple[Column, ...], dialect: str) -> list[str]:
    return [
        f"{c.name} {_type(c.sql_type, dialect)}{'' if c.nullable else ' NOT NULL'}"
        for c in columns
    ]


def _table(name: str, lines: list[str]) -> str:
    body = ",\n".join(f"    {line}" for line in lines)
    return f"CREATE TABLE {name} (\n{body}\n);\n"


def render_ddl(dialect: str = "sqlite") -> str:
    """CREATE TABLE and CREATE INDEX statements for one dialect."""
    if dialect not in DIALECTS:
        raise ValueError(f"unknown dialect: {dialect}")
    integer = _type("INTEGER", dialect)
    pk = (
        "id INTEGER PRIMARY KEY"
        if dialect == "sqlite"
        else "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    )
    file_pk = pk.replace("id ", "file_id ", 1)
    file_fk = f"file_id {integer} NOT NULL REFERENCES source_files (file_id)"
    key_columns = ", ".join(PAYMENT_KEY)

    parts = [
        f"-- Generated by payrecon.db.render_ddl({dialect!r}); do not edit by hand.\n"
        "-- Staging tables are permissive on purpose: dirty rows must be storable so\n"
        "-- the SQL checks can report them.\n\n",
        _table("run_meta", ["key TEXT PRIMARY KEY", "value TEXT NOT NULL"]),
        "\n",
        _table(
            "source_files",
            [
                file_pk,
                "name TEXT NOT NULL",
                "kind TEXT NOT NULL",
                "provider TEXT",
                "sha256 TEXT",
                "encoding TEXT",
                "delimiter TEXT",
                f"rows_read {integer} NOT NULL",
                f"rows_staged {integer} NOT NULL",
                f"rows_rejected {integer} NOT NULL",
                "period_text TEXT",
                f"declared_paid_in_minor {integer}",
                f"declared_paid_out_minor {integer}",
                "loaded_at TEXT NOT NULL",
            ],
        ),
        "\n",
        _table(
            "statement_summary",
            [
                f"file_id {integer} NOT NULL REFERENCES source_files (file_id)",
                "label TEXT NOT NULL",
                f"paid_in_minor {integer} NOT NULL",
                f"paid_out_minor {integer} NOT NULL",
                "PRIMARY KEY (file_id, label)",
            ],
        ),
        "\n",
        _table("orders", [pk, file_fk, *_contract(ORDER_COLUMNS, dialect)]),
        "\n",
        _table("payments", [pk, file_fk, *_contract(PAYMENT_COLUMNS, dialect)]),
        "\n",
        _table(
            "load_issues",
            [pk, file_fk, f"source_row {integer} NOT NULL", "field TEXT NOT NULL", "code TEXT NOT NULL"],
        ),
        "\n",
        _table(
            "rejected_rows",
            [pk, file_fk, f"source_row {integer} NOT NULL", "reason TEXT NOT NULL", "cells_json TEXT NOT NULL"],
        ),
        "\n",
        "CREATE UNIQUE INDEX ux_source_files_content ON source_files (kind, sha256);\n",
        "CREATE INDEX ix_orders_order_id ON orders (order_id);\n",
        "CREATE INDEX ix_orders_bill_ref ON orders (bill_ref);\n",
        f"CREATE INDEX ix_payments_line_key ON payments ({key_columns});\n",
        "CREATE INDEX ix_payments_bill_ref ON payments (bill_ref);\n",
        "CREATE INDEX ix_load_issues_file ON load_issues (file_id);\n",
    ]
    return "".join(parts)


def connect(path: str | Path = ":memory:") -> sqlite3.Connection:
    """Open a SQLite connection with foreign keys enforced and rows as mappings."""
    conn = sqlite3.connect(str(path))
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def init_schema(conn: sqlite3.Connection) -> None:
    """Create every table and record the schema version and creation time."""
    conn.executescript(render_ddl("sqlite"))
    conn.executemany(
        "INSERT INTO run_meta (key, value) VALUES (?, ?)",
        [("schema_version", SCHEMA_VERSION), ("created_at", _now())],
    )
    conn.commit()


@dataclass
class Run:
    run_id: str
    path: Path
    conn: sqlite3.Connection


def new_run_db(runs_dir: str | Path, run_id: str | None = None) -> Run:
    """Create runs/<run_id>/run.db with the schema. A run id is never reused."""
    if run_id is None:
        run_id = f"{datetime.now(timezone.utc):%Y%m%dT%H%M%SZ}-{secrets.token_hex(3)}"
    if not _RUN_ID.match(run_id):
        raise ValueError("run_id may only contain letters, digits, '_' and '-'")
    path = Path(runs_dir) / run_id / "run.db"
    path.parent.mkdir(parents=True, exist_ok=False)
    conn = connect(path)
    init_schema(conn)
    return Run(run_id, path, conn)


def main(argv: list[str] | None = None, out: TextIO | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if len(args) not in (2, 3) or args[0] != "ddl" or args[1] not in DIALECTS:
        print("usage: python -m payrecon.db ddl {sqlite|postgres} [output-file]", file=sys.stderr)
        return 2
    ddl = render_ddl(args[1])
    if len(args) == 3:
        Path(args[2]).write_text(ddl, encoding="utf-8", newline="\n")
    else:
        (out or sys.stdout).write(ddl)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
