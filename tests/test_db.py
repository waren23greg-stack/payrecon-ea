import io
import sqlite3
from pathlib import Path

import pytest

from payrecon.db import (
    DIALECTS,
    SCHEMA_VERSION,
    connect,
    init_schema,
    main,
    new_run_db,
    render_ddl,
)
from payrecon.schema import (
    ORDER_COLUMNS,
    PAYMENT_COLUMNS,
    PAYMENT_KEY,
    column_names,
    required_columns,
)

SQL_DIR = Path(__file__).resolve().parents[1] / "sql"
TABLES = ("run_meta", "source_files", "statement_summary", "orders", "payments", "load_issues", "rejected_rows")


@pytest.fixture
def conn():
    connection = connect()
    init_schema(connection)
    yield connection
    connection.close()


def add_file(conn, name="a.csv", kind="payments", sha="abc"):
    cursor = conn.execute(
        "INSERT INTO source_files (name, kind, sha256, rows_read, rows_staged, rows_rejected, loaded_at)"
        " VALUES (?, ?, ?, 0, 0, 0, '2026-11-20T00:00:00Z')",
        (name, kind, sha),
    )
    return cursor.lastrowid


def add_payment(conn, file_id, **overrides):
    row = {
        "file_id": file_id, "provider": "MPESA_KE", "receipt_no": "QWE1234ABC", "kind": "PAYMENT",
        "direction": "IN", "method": "P2P", "amount_minor": 100, "currency": "KES",
        "status": "SUCCESS", "source_file": "a.csv", "source_row": 1,
    }
    row.update(overrides)
    names = ", ".join(row)
    marks = ", ".join(f":{name}" for name in row)
    conn.execute(f"INSERT INTO payments ({names}) VALUES ({marks})", row)


@pytest.mark.parametrize("dialect", DIALECTS)
def test_ddl_contains_every_contract_column_and_table(dialect):
    ddl = render_ddl(dialect)
    for table in TABLES:
        assert f"CREATE TABLE {table} (" in ddl
    for column in (*column_names(ORDER_COLUMNS), *column_names(PAYMENT_COLUMNS)):
        assert f"    {column} " in ddl
    assert f"({', '.join(PAYMENT_KEY)})" in ddl


@pytest.mark.parametrize("dialect", DIALECTS)
def test_staging_is_permissive_by_policy(dialect):
    body = "\n".join(l for l in render_ddl(dialect).splitlines() if not l.startswith("--"))
    assert "CHECK" not in body.upper()
    assert "UNIQUE INDEX ix_payments" not in body


def test_postgres_dialect_uses_identity_columns_and_64_bit_integers():
    ddl = render_ddl("postgres")
    assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl
    assert "INTEGER" not in ddl and "AUTOINCREMENT" not in ddl
    assert "amount_minor BIGINT" in ddl


def test_sqlite_dialect_uses_rowid_keys():
    ddl = render_ddl("sqlite")
    assert "id INTEGER PRIMARY KEY" in ddl and "file_id INTEGER PRIMARY KEY" in ddl
    assert "GENERATED" not in ddl


def test_unknown_dialect_is_rejected():
    with pytest.raises(ValueError):
        render_ddl("oracle")


@pytest.mark.parametrize("dialect", DIALECTS)
def test_committed_sql_files_match_the_generator(dialect):
    committed = (SQL_DIR / f"schema.{dialect}.sql").read_text(encoding="utf-8")
    assert committed == render_ddl(dialect)


def test_init_schema_creates_the_tables_and_records_the_version(conn):
    names = {r["name"] for r in conn.execute("SELECT name FROM sqlite_master WHERE type = 'table'")}
    assert set(TABLES) <= names
    meta = dict(conn.execute("SELECT key, value FROM run_meta").fetchall())
    assert meta["schema_version"] == SCHEMA_VERSION
    assert meta["created_at"].endswith("Z")


@pytest.mark.parametrize(
    ("table", "columns"), [("orders", ORDER_COLUMNS), ("payments", PAYMENT_COLUMNS)]
)
def test_staging_tables_match_the_schema_contract(conn, table, columns):
    info = conn.execute(f"PRAGMA table_info({table})").fetchall()
    assert [r["name"] for r in info][:2] == ["id", "file_id"]
    actual = {r["name"]: (r["type"], bool(r["notnull"])) for r in info[2:]}
    expected = {c.name: (c.sql_type, not c.nullable) for c in columns}
    assert actual == expected
    assert [r["name"] for r in info[2:]] == list(column_names(columns))


def test_foreign_keys_are_enforced(conn):
    with pytest.raises(sqlite3.IntegrityError):
        add_payment(conn, file_id=999)


def test_staging_accepts_dirty_values_that_the_checks_must_see(conn):
    file_id = add_file(conn)
    add_payment(conn, file_id, status="WEIRD", amount_minor=-5, receipt_no=None)
    add_payment(conn, file_id, amount_minor=None)
    add_payment(conn, file_id)
    add_payment(conn, file_id)  # same line key twice: the duplicate check must be able to see it
    assert conn.execute("SELECT COUNT(*) FROM payments").fetchone()[0] == 4
    duplicates = conn.execute(
        "SELECT COUNT(*) FROM (SELECT 1 FROM payments WHERE receipt_no IS NOT NULL"
        " GROUP BY provider, receipt_no, kind, direction HAVING COUNT(*) > 1)"
    ).fetchone()[0]
    assert duplicates == 1


@pytest.mark.parametrize("column", required_columns(PAYMENT_COLUMNS))
def test_required_payment_columns_cannot_be_null(conn, column):
    file_id = add_file(conn)
    with pytest.raises(sqlite3.IntegrityError):
        add_payment(conn, file_id, **{column: None})


def test_the_same_file_content_cannot_be_loaded_twice(conn):
    add_file(conn, "orders.csv", "orders", sha="same")
    add_file(conn, "payments.csv", "payments", sha="same")  # different kind: allowed
    with pytest.raises(sqlite3.IntegrityError):
        add_file(conn, "copy.csv", "orders", sha="same")


def test_each_run_gets_its_own_database_file(tmp_path):
    first, second = new_run_db(tmp_path), new_run_db(tmp_path)
    try:
        assert first.run_id != second.run_id
        assert first.path != second.path and first.path.exists() and second.path.exists()
        assert first.path.parent.parent == tmp_path
        add_file(first.conn)
        first.conn.commit()
        assert second.conn.execute("SELECT COUNT(*) FROM source_files").fetchone()[0] == 0
    finally:
        first.conn.close()
        second.conn.close()


def test_a_run_id_is_never_reused(tmp_path):
    run = new_run_db(tmp_path, "run-1")
    run.conn.close()
    with pytest.raises(FileExistsError):
        new_run_db(tmp_path, "run-1")


@pytest.mark.parametrize("bad", ["../escape", "a/b", "a b", "", "x" * 65, "..\\up"])
def test_a_run_id_cannot_escape_the_runs_folder(tmp_path, bad):
    with pytest.raises(ValueError):
        new_run_db(tmp_path, bad)


def test_command_line_prints_or_writes_ddl(tmp_path):
    out = io.StringIO()
    assert main(["ddl", "sqlite"], out=out) == 0
    assert out.getvalue() == render_ddl("sqlite")
    target = tmp_path / "schema.sql"
    assert main(["ddl", "postgres", str(target)]) == 0
    assert target.read_bytes() == render_ddl("postgres").encode("utf-8")
    assert b"\r" not in target.read_bytes()


@pytest.mark.parametrize("args", [[], ["ddl"], ["ddl", "oracle"], ["dump", "sqlite"], ["ddl", "sqlite", "a", "b"]])
def test_command_line_rejects_bad_arguments(args):
    assert main(args) == 2
